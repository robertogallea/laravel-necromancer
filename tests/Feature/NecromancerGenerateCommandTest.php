function putKnowledgeBundle(string $relativeDir, array $index): void
{
    File::ensureDirectoryExists(base_path($relativeDir));
    File::put(base_path($relativeDir.'/bundle.json'), json_encode($index, JSON_THROW_ON_ERROR));
}

